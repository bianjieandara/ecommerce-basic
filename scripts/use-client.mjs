// Generates the root wrangler.jsonc for one client by merging wrangler.base.jsonc with clients/<slug>/client.jsonc.
// Usage: node scripts/use-client.mjs [slug]   (default: CLIENT_SLUG env var, then "demo")
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'jsonc-parser';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Reads and parses a JSONC file, failing loudly when it is missing.
 * @param {string} path Absolute path to the file.
 * @returns {any} Parsed JSON value.
 */
export function readJsonc(path) {
  if (!existsSync(path)) throw new Error(`Missing file: ${path}`);
  const errors = [];
  const value = parse(readFileSync(path, 'utf8'), errors, { allowTrailingComma: true });
  if (errors.length > 0) throw new Error(`Invalid JSONC in ${path} (offset ${errors[0].offset})`);
  return value;
}

/**
 * Builds the placeholder map (`__NAME__` -> value) for one client.
 * Rate-limit namespace ids are derived from `rateLimitNamespaceBase`, so they stay unique per client.
 * @param {any} client Parsed clients/<slug>/client.jsonc.
 * @returns {Record<string, string>} Placeholder values.
 */
export function buildPlaceholders(client) {
  const base = Number(client.rateLimitNamespaceBase);
  if (!Number.isInteger(base) || base < 1)
    throw new Error('rateLimitNamespaceBase must be a positive integer');
  return {
    D1_NAME: client.d1.name,
    D1_ID: client.d1.id,
    R2_BUCKET: client.r2.bucket,
    KV_ID: client.kv.id,
    QUEUE: client.queue.name,
    DLQ: client.queue.dlq,
    CRON: client.cron,
    AE_DATASET: client.analyticsDataset,
    RL_AUTH: String(base + 1),
    RL_FORMS: String(base + 2),
    RL_API: String(base + 3),
  };
}

/**
 * Recursively replaces `__NAME__` tokens in every string of a JSON value.
 * Throws when a token has no value, so a missing client field can never reach a deploy.
 * @param {unknown} value JSON value to rewrite.
 * @param {Record<string, string>} placeholders Values to substitute.
 * @returns {unknown} Rewritten value.
 */
export function replacePlaceholders(value, placeholders) {
  if (typeof value === 'string') {
    const out = value.replace(/__([A-Z0-9_]+)__/g, (token, key) => {
      if (!(key in placeholders)) throw new Error(`Unknown placeholder ${token}`);
      return placeholders[key];
    });
    return out;
  }
  if (Array.isArray(value)) return value.map((item) => replacePlaceholders(item, placeholders));
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => [k, replacePlaceholders(v, placeholders)]),
    );
  }
  return value;
}

/**
 * Produces the merged Wrangler configuration for one client.
 * @param {any} base Parsed wrangler.base.jsonc.
 * @param {any} client Parsed clients/<slug>/client.jsonc.
 * @returns {any} Final configuration object (not yet serialized).
 */
export function mergeClientConfig(base, client) {
  const config = replacePlaceholders(base, buildPlaceholders(client));
  config.name = client.workerName;
  config.vars = { ...config.vars, ...client.vars, CLIENT_SLUG: client.slug };
  if (client.accountId) config.account_id = client.accountId;
  if (Array.isArray(client.customDomains) && client.customDomains.length > 0) {
    config.routes = client.customDomains.map((domain) => ({ pattern: domain, custom_domain: true }));
  }
  return config;
}

/** CLI entry: writes the root wrangler.jsonc for the selected client. */
function main() {
  const slug = process.argv[2] || process.env.CLIENT_SLUG || 'demo';
  const base = readJsonc(join(ROOT, 'wrangler.base.jsonc'));
  const client = readJsonc(join(ROOT, 'clients', slug, 'client.jsonc'));
  const config = mergeClientConfig(base, client);
  const header = `// GENERATED by scripts/use-client.mjs for client "${slug}". Edit wrangler.base.jsonc or clients/${slug}/client.jsonc.\n`;
  writeFileSync(join(ROOT, 'wrangler.jsonc'), header + JSON.stringify(config, null, 2) + '\n');
  console.log(`[use-client] wrote wrangler.jsonc for "${slug}" (worker: ${client.workerName})`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
